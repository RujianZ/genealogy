/**
 * 本人条目里写的那个父名，取出来用于**比对**。
 *
 * ★ 为什么要单独一个函数
 *
 *   谱上写父子关系有两种句式，**分册不同**：
 *
 *       前三册（1710–1992 历届的旧文）   「光量公长子」   父名 + 排行
 *       第四册（2016 年新写的）           「承华之长子」   父名 + 之 + 排行
 *
 *   上游解析按前一种切，碰上后一种就把「之」当成了名字的一部分，
 *   於是 father_name 变成「承华之」「开聪公之」——19 人。
 *
 *   19 人里 18 人没受影响，因为他们的父边是从**父亲那边的生子名单**
 *   反过来接上的（rank 1）；只有承贵（第27世，册4·卷八·第137页）
 *   谱上明写「开聪公之祧子」，两边都指望这个父名，结果一条边都没有。
 *
 * ★ 「之」是虚词，不是名字。切掉它是**还原谱写的字**，不是改写。
 *   界面上照旧显示谱上原样的「承华之长子」（father_name + filiation 拼回去）。
 *   这里只管比对。
 *
 * ★ 只切结尾的「之」。名字中间带之的（若有）一个不碰。
 */
import { norm } from './norm.ts';

/** 比对用：折叠异体、去空白、去掉句末的虚词「之」 */
export function fname(s: string | null | undefined): string {
  return norm(s ?? '').replace(/[\s　]/g, '')
    // ★ 开头粘上的**字段标记**。谱上一格里是「…字某某」紧接着下一位的父名，
    //   切在了错的地方：梁昌（册2·卷四·第360页）的父名成了「**字**泽渚」。
    //   父名不可能以「字／讳／号／名」起头，这几个是标记不是名字，剥掉。
    //
    //   ★ 结尾粘的排行字（「啟尚**长**」「铣忠**以**」）**不剥**——
    //     「光长」本身就是人名（壁温的父亲），一剥就误伤。那两条进人工清单。
    .replace(/^[字讳諱号號名](?=.{2,})/, '')
    .replace(/之$/, '');
}

/**
 * 显示用：把谱上那句话拼回原样。
 * 「承华之」+「长子」→「承华之长子」；「光量」+「长子」→「光量长子」。
 */
export function writtenAs(fatherName: string | null | undefined,
                          filiation: string | null | undefined): string {
  const f = (fatherName ?? '').trim();
  if (!f) return '';
  return f + (filiation ?? '');
}
