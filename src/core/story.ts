/**
 * 这一段到底是不是「事迹」。
 *
 * ★ 问题：现在 1,667 段里只有约 107 段是真事迹，其余 94% 是噪音。
 *
 *   「公妣俱厝云山中棚庄屋东边附曾祖母及祖墓右同向立胞弟光治四子壁铨为嗣
 *     黄妣殁于民国三年甲寅七月初一日辰时」
 *
 *   这不是事迹，是**这条记录自己的字段**——葬、立嗣、妣殁——连排在一起，
 *   只不过解析器没能把它们切开，剩下的就被当成事迹收了进来。
 *   跟「假人」是同一个根因：切不开字段，剩下的就被当成了一个新东西。
 *
 * ★ 判法：真事迹一定有**叙述的痕迹**。
 *     人称    公、吾、余、予
 *     评语    孝、义、节、烈、贞、殉、旌、赞
 *     连词    因、故、遂、虽、然、每、尝
 *     动作    读书、从军、捐躯、经商、迁徙
 *   纯字段串一个都没有：葬X向Y、殁于某年、立某为嗣、生子N、娶某氏。
 *
 * ★ 数据一条没删。这里只决定**摆不摆出来当事迹**，
 *   原文照旧在本人卡片底部的「谱上原文」里，一个字不少。
 */

const NS = (s: string | null | undefined) => (s ?? '').replace(/[\s　]/g, '');

/** 谱的固定格式——这些出现多少次都不算叙述 */
const FIELD = [
  /[葬厝][^，。]{0,20}?向/, /^[葬厝附合俱]/, /殁于|殁於|卒于|卒於|生于|生於/,
  /立[^，。]{0,12}为嗣/, /生子[一二三四五六七八九十两]/, /女[一二三四五六七八九十两]/,
  /[娶配妣聘][^，。]{0,6}氏/, /年[一二三四五六七八九十]+$/,
  /有碑|合墓|同向|附父墓|附母墓/,
];

/** 叙述的痕迹——有一处就算 */
const NARRATIVE = [
  /公[性行素少幼晚为其以事居尝甞尤好善]/, /[吾余予]/, /者也|矣$|焉$|乎$|哉/,
  /孝|义|節|节|烈|贞|捐躯|殉|旌|奖|赞|传|痛|哀|悲|念|忆|谨述|谨撰|拜撰/,
  /因|故|遂|乃|遇|值|尝|甞|每|虽|然而|则/,
  /读书|考试|不遇|从军|参军|入伍|毕业|大学|工作|经商|贸易|行医|教书/,
  /抚孤|守节|柏舟|闺范|无后|绩纺|治家|勤俭|力田/,
];

export interface StoryLike {
  text: string;
  chars?: number;
  cn?: string;
  kinds?: string[];
}

/**
 * 摆不摆出来当事迹。**只看正文，不看有没有今译。**
 *
 * ★ 一开始写的是「有今译的一律留」，错了：266 条今译里 **189 条是
 *   「按格式译」**——正是那些纯字段串的公式化翻译（「立X为嗣」→「立某某为嗣子」）。
 *   拿它当「这是真事迹」的凭据，等於用自己上一轮的产物给自己背书。
 *
 * · 太短的不算（「元至正辛巳年七」这种是日期碎片）
 * · 有叙述痕迹的算
 * · 很长、又几乎没有字段格式的算（叙述不一定用得上那几个词）
 */
export function isStory(x: StoryLike): boolean {
  const t = NS(x.text);
  if (t.length < 12) return false;
  if (NARRATIVE.some(r => r.test(t))) return true;
  return t.length >= 30 && FIELD.filter(r => r.test(t)).length <= 1;
}

