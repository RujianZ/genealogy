/**
 * 这部谱一条记录的**语法**。
 *
 * 翻二十页就看得出来，每一条都是这个顺序写的：
 *
 *     承 健                     ← 名字（两个字中间空开）
 *     开赛之子                   ← 父名＋排行（也可能只写在页眉上，右起横排）
 *     字儒健                     ← 字／讳／号／名
 *     庠生                       ← 功名
 *     生于
 *     一九九九年五月十五日子时      ← 标签一行，值另起一行
 *     殁于
 *     …
 *     年六十五                    ← 寿
 *     葬云山私山窊向南             ← 葬
 *     娶周氏                      ← 配偶（娶／妣／继娶／复娶／聘）
 *     生于 …                      ← 配偶的生殁葬，跟在她后面
 *     生子三
 *              梁枸              ← 名字缩进
 *                架              ← 单字＝共用上一个的辈字
 *                柴
 *     女一适潘
 *     〔传赞、迁徙、事迹…〕         ← 剩下的散文
 *
 * ★ 把语法写出来，才能问三件事：
 *     记漏了吗——原文里有值，字段里却是空的
 *     记错了吗——字段里有字，原文里找不到（除非来自页眉）
 *     没归属的到底是什么——是散文（合理），还是我们没读懂（要查）
 *
 * ★ 标签本身不是内容。「生于」两个字不进任何字段，那不叫漏。
 */

/** 一行是什么 */
export type LineKind =
  | '名字' | '父名' | '字号' | '功名'
  | '标签'          // 生于／殁于／生子三／女二 这类只起头的
  | '日期'          // 年号或公元纪年
  | '寿'
  | '葬'
  | '配偶'
  | '子女名'        // 名单里缩进的名字
  | '散文'          // 传赞、迁徙、事迹
  | '页码水印'      // 「张氏宗谱卷…公元二零一六年」印在版心的
  | '空';

const NS = (s: string) => (s ?? '').replace(/[\s　]/g, '');

const RE = {
  父名: /^(.{1,4})(公)?(之子|长子|次子|三子|四子|五子|六子|七子|八子|九子|幼子|季子|嗣子|祧子|继子|养子|之女)$/,
  字号: /^(字|讳|号|名)./,
  标签: /^(生于|生於|殁于|殁於|卒于|卒於|公殁于|妣殁于|生|殁|葬|生子[一二三四五六七八九十两]?|女[一二三四五六七八九十两]|娶|妣|配|继娶|復娶|复娶|继配|聘|側室|侧室)$/,
  日期: /^(明|清|大清|民国|中华民国)?[一二三四五六七八九十百千零〇0-9]{1,}(年|世纪)|^[甲乙丙丁戊己庚辛壬癸][子丑寅卯辰巳午未申酉戌亥]|^(洪武|永乐|宣德|正统|景泰|天顺|成化|弘治|正德|嘉靖|隆庆|万历|泰昌|天启|崇祯|崇正|顺治|康熙|雍正|乾隆|嘉庆|道光|咸丰|同治|光绪|宣统)/,
  寿: /^(年|享寿|寿|享年)[一二三四五六七八九十百]/,
  葬: /^(葬|附葬|合葬|俱葬|厝|安厝)/,
  配偶: /^(娶|妣|配|继娶|復娶|复娶|继配|聘|又娶|又妣|側室|侧室|原配|元配)./,
  功名: /^(庠生|廪生|贡生|监生|太学生|国学生|儒士|业儒|职员|大学生|中专|高中|例赠|敕封|军官|烈士)/,
  水印: /^(张氏宗谱|張氏宗譜|公元二零一六年|卷[一二三四五六七八九十])$/,
};

/** 这一行是什么。**只按形状判，不看它属于谁。** */
export function classify(line: string): LineKind {
  const t = NS(line);
  if (!t) return '空';
  if (RE.水印.test(t)) return '页码水印';
  if (RE.标签.test(t)) return '标签';
  if (RE.父名.test(t)) return '父名';
  if (RE.字号.test(t)) return '字号';
  if (RE.功名.test(t)) return '功名';
  if (RE.寿.test(t)) return '寿';
  if (RE.葬.test(t)) return '葬';
  if (RE.配偶.test(t)) return '配偶';
  if (RE.日期.test(t)) return '日期';
  // 短、又不像句子的，多半是名单里的名字
  if (t.length <= 4 && !/[，。；、于於也矣]/.test(t)) return '子女名';
  return '散文';
}

/** 整条记录逐行分类。第一行永远是名字。 */
export function lines(raw: string): { text: string; kind: LineKind }[] {
  const ls = (raw ?? '').split('\n');
  const out: { text: string; kind: LineKind }[] = [];
  let first = true;
  for (const l of ls) {
    if (!NS(l)) continue;
    if (first) { out.push({ text: l, kind: '名字' }); first = false; continue; }
    out.push({ text: l, kind: classify(l) });
  }
  return out;
}
