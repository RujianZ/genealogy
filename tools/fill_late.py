bad = []
for doc, (head, sig, paras) in DOCS.items():
    got = HAN(head) + "".join(HAN(s) for s, *_ in paras) + HAN(sig)
    want = HAN(SHOU[doc])
    if got != want:
        k = next((j for j in range(min(len(got), len(want))) if got[j] != want[j]),
                 min(len(got), len(want)))
        bad.append(f"{doc}：拼出 {len(got)} 字，原文 {len(want)} 字，第 {k} 字起分岔\n"
                   f"      拼出 …{got[max(0,k-14):k+14]}…\n"
                   f"      原文 …{want[max(0,k-14):k+14]}…")
if bad:
    print("✘ 原文对不上，没有写文件：\n  " + "\n  ".join(bad))
    sys.exit(1)

